-- RL-33 payment request verification workflow
create table if not exists public.payment_requests (
  id bigint generated by default as identity primary key,
  student_id text not null references public.students(id) on delete cascade,
  utr text not null,
  amount numeric(10,2) not null check (amount > 0),
  fee_month date not null check (extract(day from fee_month) = 1),
  status text not null default 'Pending' check (status in ('Pending','Approved','Rejected')),
  submitted_at timestamptz not null default now(),
  verified_at timestamptz,
  verified_by uuid references auth.users(id)
);
alter table public.payment_requests enable row level security;
drop policy if exists "student create own payment request" on public.payment_requests;
create policy "student create own payment request" on public.payment_requests for insert to authenticated
with check (student_id = public.current_student_id() and status = 'Pending');
drop policy if exists "student read own payment requests" on public.payment_requests;
create policy "student read own payment requests" on public.payment_requests for select to authenticated
using (student_id = public.current_student_id());
drop policy if exists "admin manage payment requests" on public.payment_requests;
create policy "admin manage payment requests" on public.payment_requests for all to authenticated
using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');
