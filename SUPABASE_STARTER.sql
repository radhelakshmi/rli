-- RL-INSTITUTE secure backend starter for Supabase/PostgreSQL
-- Run in a fresh TEST project first. Review and test all RLS policies.
-- Never place the Supabase service_role key in browser code or GitHub.
create extension if not exists pgcrypto;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  login_id text unique not null,
  role text not null check (role in ('admin','student','parent')),
  student_id text,
  created_at timestamptz not null default now(),
  check ((role = 'admin' and student_id is null) or role <> 'admin')
);
create table if not exists public.class_fee_rates (
  id bigint generated by default as identity primary key,
  class_name text not null unique,
  monthly_fee numeric(10,2) not null check (monthly_fee >= 0),
  active boolean not null default true,
  updated_at timestamptz not null default now()
);
create table if not exists public.students (
  id text primary key,
  full_name text not null,
  class_name text not null,
  parent_name text,
  parent_phone text,
  monthly_fee numeric(10,2) not null default 0 check (monthly_fee >= 0),
  joining_date date,
  status text not null default 'Active' check (status in ('Active','Inactive')),
  notes text,
  created_at timestamptz not null default now()
);
alter table public.profiles drop constraint if exists profiles_student_id_fkey;
alter table public.profiles add constraint profiles_student_id_fkey
  foreign key (student_id) references public.students(id) on delete set null;

create table if not exists public.attendance (
  id bigint generated by default as identity primary key,
  student_id text not null references public.students(id) on delete cascade,
  attendance_date date not null,
  status text not null check (status in ('Present','Absent','Late','Leave')),
  marked_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  unique (student_id, attendance_date)
);
create table if not exists public.fee_payments (
  id bigint generated by default as identity primary key,
  receipt_number text unique not null,
  student_id text not null references public.students(id) on delete cascade,
  amount numeric(10,2) not null check (amount > 0),
  payment_date date not null default current_date,
  payment_method text not null default 'Cash',
  fee_month date not null,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now(),
  check (extract(day from fee_month) = 1)
);
create table if not exists public.test_marks (
  id bigint generated by default as identity primary key,
  student_id text not null references public.students(id) on delete cascade,
  test_name text not null,
  test_date date not null default current_date,
  marks_obtained numeric(7,2) not null check (marks_obtained >= 0),
  total_marks numeric(7,2) not null check (total_marks > 0 and marks_obtained <= total_marks),
  teacher_remark text,
  created_at timestamptz not null default now()
);

create or replace function public.current_user_role()
returns text language sql stable security definer set search_path = public
as $$ select role from public.profiles where user_id = auth.uid() limit 1 $$;
create or replace function public.current_student_id()
returns text language sql stable security definer set search_path = public
as $$ select student_id from public.profiles where user_id = auth.uid() and role = 'student' limit 1 $$;

alter table public.profiles enable row level security;
alter table public.class_fee_rates enable row level security;
alter table public.students enable row level security;
alter table public.attendance enable row level security;
alter table public.fee_payments enable row level security;
alter table public.test_marks enable row level security;

drop policy if exists "profile read own or admin" on public.profiles;
create policy "profile read own or admin" on public.profiles for select to authenticated
using (user_id = auth.uid() or public.current_user_role() = 'admin');
drop policy if exists "admin manage profiles" on public.profiles;
create policy "admin manage profiles" on public.profiles for all to authenticated
using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');

drop policy if exists "admin manage class fee rates" on public.class_fee_rates;
create policy "admin manage class fee rates" on public.class_fee_rates for all to authenticated
using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');

drop policy if exists "admin manage students" on public.students;
create policy "admin manage students" on public.students for all to authenticated
using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');
drop policy if exists "student read own student row" on public.students;
create policy "student read own student row" on public.students for select to authenticated
using (id = public.current_student_id());

drop policy if exists "admin manage attendance" on public.attendance;
create policy "admin manage attendance" on public.attendance for all to authenticated
using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');
drop policy if exists "student read own attendance" on public.attendance;
create policy "student read own attendance" on public.attendance for select to authenticated
using (student_id = public.current_student_id());

drop policy if exists "admin manage fee payments" on public.fee_payments;
create policy "admin manage fee payments" on public.fee_payments for all to authenticated
using (public.current_user_role() = 'admin') with check (public.current_user_role() = 'admin');
drop policy if exists "student read own fee payments" on public.fee_payments;
create policy "student read own fee payments" on public.fee_payments for select to authenticated
